#!/usr/bin/env bash
# Create a tiny BLAST nucleotide database for local testing and E2E tests.
#
# Usage:
#   ./scripts/seed_test_db.sh [output_dir]
#
# Output: /tmp/blast_test_db/test_seqs.{nhr,nin,nsq}
# Set BLAST_DB_DIR=/tmp/blast_test_db in your .env to use it.

set -euo pipefail

OUT_DIR="${1:-/tmp/blast_test_db}"
mkdir -p "${OUT_DIR}"

FASTA="${OUT_DIR}/test_seqs.fasta"

cat > "${FASTA}" <<'FASTA'
>seq_alpha
ATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGC
ATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGCATGC
>seq_beta
TTTTAAAACCCCGGGGTTTTAAAACCCCGGGGTTTTAAAACCCCGGGGTTTTAAAACCCCGGGG
TTTTAAAACCCCGGGGTTTTAAAACCCCGGGGTTTTAAAACCCCGGGGTTTTAAAACCCCGGGG
>seq_gamma
GCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGC
GCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGCGC
>seq_delta
AAAAGGGGCCCCTTTTAAAAGGGGCCCCTTTTAAAAGGGGCCCCTTTTAAAAGGGGCCCCTTTT
AAAAGGGGCCCCTTTTAAAAGGGGCCCCTTTTAAAAGGGGCCCCTTTTAAAAGGGGCCCCTTTT
>seq_epsilon
ACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGT
ACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGTACGT
FASTA

makeblastdb \
    -in "${FASTA}" \
    -dbtype nucl \
    -out "${OUT_DIR}/test_seqs" \
    -title "Test sequences"

echo ""
echo "Database created at: ${OUT_DIR}/test_seqs"
echo "Add to your .env:"
echo "  BLAST_DB_DIR=${OUT_DIR}"
